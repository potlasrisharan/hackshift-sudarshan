/** Compatibility adapter for the old icon-font names. All glyphs are now local SVGs. */
export function SymbolIcon({
  children,
  ...props
}: HTMLAttributes<HTMLSpanElement> & { children?: ReactNode }) {
  const name = typeof children === "string" ? children.trim() : "";
  const Glyph = icons[name as keyof typeof icons] ?? CircleHelp;
  return (
    <span {...props} aria-hidden="true">
      <Glyph size={20} strokeWidth={1.7} />
    </span>
  );
}
